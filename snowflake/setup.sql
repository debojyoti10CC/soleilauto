-- Run in a Snowflake database/schema and replace SOLEIL_SEARCH_WH with your warehouse.
-- Public product docs only; do not load wallet keys or private user prompts.
CREATE TABLE IF NOT EXISTS SOLEIL_EVIDENCE (
  ID VARCHAR,
  TITLE VARCHAR,
  CONTENT VARCHAR,
  SOURCE_URL VARCHAR,
  UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE CORTEX SEARCH SERVICE SOLEIL_EVIDENCE_SEARCH
  ON CONTENT
  ATTRIBUTES TITLE, SOURCE_URL
  WAREHOUSE = SOLEIL_SEARCH_WH
  TARGET_LAG = '1 hour'
  AS SELECT TITLE, CONTENT, SOURCE_URL FROM SOLEIL_EVIDENCE;
